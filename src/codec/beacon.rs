//! Encoding and validation of fixed-size discovery beacons.
//!
//! Callers supply the extracted manufacturer payload, without BLE headers
//! or the company identifier. Decoded peer fields are unauthenticated.

use crate::BeaconError;

/// Size of one encoded beacon payload, excluding the BLE manufacturer wrapper.
pub const BEACON_LEN: usize = 16;

/// Initial beacon wire version supported by this codec.
pub const BEACON_VERSION: u8 = 1;

const ACCEPTING: u8 = 1 << 0;
const RELAY_WILLING: u8 = 1 << 1;
const LOW_BATTERY: u8 = 1 << 2;
const KNOWN_FLAGS: u8 = ACCEPTING | RELAY_WILLING | LOW_BATTERY;

/// The three supported beacon flags, represented without reserved bits.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct BeaconFlags {
    /// The sender currently accepts new links.
    pub accepting: bool,
    /// The sender is willing to relay traffic.
    pub relay_willing: bool,
    /// The sender reports low battery.
    pub low_battery: bool,
}

impl BeaconFlags {
    fn to_bits(self) -> u8 {
        let mut bits = 0;
        if self.accepting {
            bits |= ACCEPTING;
        }
        if self.relay_willing {
            bits |= RELAY_WILLING;
        }
        if self.low_battery {
            bits |= LOW_BATTERY;
        }
        bits
    }

    fn from_bits(bits: u8) -> Result<Self, BeaconError> {
        let unknown = bits & !KNOWN_FLAGS;
        if unknown != 0 {
            return Err(BeaconError::UnsupportedFlags { unknown });
        }
        Ok(Self {
            accepting: bits & ACCEPTING != 0,
            relay_willing: bits & RELAY_WILLING != 0,
            low_battery: bits & LOW_BATTERY != 0,
        })
    }
}

/// A discovery announcement with opaque hint and digest bytes.
///
/// Encoding and decoding allocate no heap memory.
///
/// # Example
///
/// ```
/// use ao_network::{BEACON_LEN, BEACON_VERSION, Beacon, BeaconFlags};
///
/// let beacon = Beacon {
///     flags: BeaconFlags {
///         accepting: true,
///         relay_willing: true,
///         low_battery: false,
///     },
///     degree: 3,
///     max_links: 5,
///     hint: [0xA5; 8],
///     digest: [0x5A; 4],
/// };
/// let bytes = beacon.encode();
/// assert_eq!(bytes.len(), BEACON_LEN);
/// assert_eq!(bytes[0], BEACON_VERSION);
/// assert_eq!(Beacon::decode(&bytes)?, beacon);
/// # Ok::<(), ao_network::BeaconError>(())
/// ```
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Beacon {
    /// Flags reported by the sender.
    pub flags: BeaconFlags,
    /// Claimed current neighbour count; topology validates its usefulness.
    pub degree: u8,
    /// Claimed link capacity, not a replacement for our own validated config.
    pub max_links: u8,
    /// Opaque discovery hint generated by the identity layer.
    pub hint: [u8; 8],
    /// Opaque store digest supplied by the mesh layer.
    pub digest: [u8; 4],
}

impl Beacon {
    /// Encodes this announcement as exactly one version-1 beacon payload.
    pub fn encode(&self) -> [u8; BEACON_LEN] {
        let mut bytes = [0; BEACON_LEN];
        bytes[0] = BEACON_VERSION;
        bytes[1] = self.flags.to_bits();
        bytes[2] = self.degree;
        bytes[3] = self.max_links;
        bytes[4..12].copy_from_slice(&self.hint);
        bytes[12..16].copy_from_slice(&self.digest);
        bytes
    }

    /// Decodes exactly one beacon payload without allocation or I/O.
    ///
    /// # Errors
    ///
    /// Returns [`BeaconError`] if the length is not exactly [`BEACON_LEN`],
    /// the version is unsupported or reserved flag bits are set, in that
    /// order. Length is checked before any indexing or slice copies.
    pub fn decode(bytes: &[u8]) -> Result<Self, BeaconError> {
        if bytes.len() != BEACON_LEN {
            return Err(BeaconError::InvalidLength {
                expected: BEACON_LEN,
                actual: bytes.len(),
            });
        }
        if bytes[0] != BEACON_VERSION {
            return Err(BeaconError::UnsupportedVersion { version: bytes[0] });
        }
        let flags = BeaconFlags::from_bits(bytes[1])?;
        let mut hint = [0; 8];
        let mut digest = [0; 4];
        hint.copy_from_slice(&bytes[4..12]);
        digest.copy_from_slice(&bytes[12..16]);
        Ok(Self {
            flags,
            degree: bytes[2],
            max_links: bytes[3],
            hint,
            digest,
        })
    }
}
