//! Core value types shared by every layer of the crate.
//!
//! All types here are small, `Copy` where possible and allocation-free: they
//! are passed by value on hot paths (scheduling, maps, event payloads) and
//! never hold unbounded input from the wire.

/// Stable identifier of a link on *this* node.
///
/// Allocated monotonically by the link manager and never sent on the wire:
/// each endpoint names the same connection with its own id, so ids are purely
/// local. A `u64` keeps wrap-around out of reach for any realistic lifetime,
/// including long fuzzing or simulation runs.
///
/// # Example
///
/// ```
/// use ao_network::LinkId;
/// use std::collections::HashMap;
///
/// let a = LinkId::new(1);
/// let b = LinkId::new(2);
/// let mut map: HashMap<LinkId, &str> = HashMap::new();
/// map.insert(a, "first");
/// assert_eq!(map[&a], "first");
/// assert_ne!(a, b);
/// assert_eq!(a.raw(), 1);
/// ```
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct LinkId(u64);

impl LinkId {
    /// Creates a `LinkId` from its raw representation.
    ///
    /// Production callers get ids from the link manager; `new` exists for
    /// tests, sim scripts and log/trace reconstruction.
    pub const fn new(raw: u64) -> Self {
        Self(raw)
    }

    /// The raw value of this link id.
    pub const fn raw(self) -> u64 {
        self.0
    }
}

/// Opaque, fixed-size key identifying a radio peer.
///
/// Supplied by the transport (typically a 128-bit truncation of the peer's
/// BLE address or an address hash) and treated as opaque bytes here:
/// `aoNetwork` never interprets, derives or validates its contents.
/// Fixed-size so it is `Copy`, allocation-free and cheap as a map key in the
/// peer table (NET-15).
///
/// # Example
///
/// ```
/// use ao_network::PeerKey;
///
/// let key = PeerKey::new([7u8; 16]);
/// assert_eq!(key.as_bytes(), &[7u8; 16]);
/// assert_eq!(PeerKey::from([7u8; 16]), key);
/// ```
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct PeerKey([u8; 16]);

impl PeerKey {
    /// Creates a key from 16 opaque bytes.
    pub const fn new(bytes: [u8; 16]) -> Self {
        Self(bytes)
    }

    /// The raw bytes of this key.
    pub const fn as_bytes(&self) -> &[u8; 16] {
        &self.0
    }
}

impl From<[u8; 16]> for PeerKey {
    fn from(bytes: [u8; 16]) -> Self {
        Self::new(bytes)
    }
}

/// The rotating link tag generated by `aoIdents` and passed down by `aoMesh`.
///
/// `aoNetwork` carries it in the `Hello` exchange and uses it **only** for
/// duplicate-link tie-breaking (NET-17). Its contents are opaque here — no
/// cryptography, validation or derivation happens in this crate.
///
/// # Example
///
/// ```
/// use ao_network::LocalTag;
///
/// let tag = LocalTag::new([9u8; 16]);
/// assert_eq!(tag.as_bytes(), &[9u8; 16]);
/// ```
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct LocalTag([u8; 16]);

impl LocalTag {
    /// Creates a tag from 16 opaque bytes.
    pub const fn new(bytes: [u8; 16]) -> Self {
        Self(bytes)
    }

    /// The raw bytes of this tag.
    pub const fn as_bytes(&self) -> &[u8; 16] {
        &self.0
    }
}

impl From<[u8; 16]> for LocalTag {
    fn from(bytes: [u8; 16]) -> Self {
        Self::new(bytes)
    }
}

/// Which side of the connection opened the link.
///
/// Decides who sends `Hello` first and how the handshake state machine
/// (NET-10) is parameterised. The set is closed: BLE has exactly two roles.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum LinkRole {
    /// Opened the connection (BLE central side).
    Initiator,
    /// Accepted the connection (BLE peripheral side).
    Responder,
}

/// The four scheduling channels every frame belongs to.
///
/// Scheduling rules (strict priority, deficit round-robin weights) live in the
/// send queue (NET-11); this enum only names the channels. The set is fixed by
/// the protocol and will not grow — new *frame types* are added to the codec,
/// not as channels.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Channel {
    /// Link management and acks: strict priority, never delayed by bulk.
    Control,
    /// Direct and broadcast packets: deficit round-robin, weight ~4.
    Message,
    /// Latest-wins data such as location: coalescing, never `QueueFull`.
    Telemetry,
    /// Sync transfers: deficit round-robin, weight ~1.
    Bulk,
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashMap;

    #[test]
    fn link_id_round_trips_and_orders() {
        let id = LinkId::new(u64::MAX);
        assert_eq!(id.raw(), u64::MAX);
        assert!(LinkId::new(1) < LinkId::new(2));
        assert_eq!(LinkId::new(7), LinkId::new(7));
    }

    #[test]
    fn keys_are_usable_as_map_keys() {
        let mut map: HashMap<PeerKey, LinkRole> = HashMap::new();
        map.insert(PeerKey::new([1; 16]), LinkRole::Initiator);
        map.insert(PeerKey::from([2; 16]), LinkRole::Responder);
        assert_eq!(map.len(), 2);
        assert_eq!(map[&PeerKey::new([1; 16])], LinkRole::Initiator);
    }

    #[test]
    fn tag_and_key_dont_collide_across_types() {
        // Same bytes, different newtypes: the type system keeps the peer
        // table and the duplicate-link tie-break from being confused.
        let key = PeerKey::new([5; 16]);
        let tag = LocalTag::new([5; 16]);
        assert_eq!(key.as_bytes(), tag.as_bytes());
        assert_eq!(key, PeerKey::from([5; 16]));
        assert_eq!(tag, LocalTag::from([5; 16]));
    }

    #[test]
    fn every_channel_and_role_exists() {
        // Compile-time guard for the documented sets.
        let roles = [LinkRole::Initiator, LinkRole::Responder];
        assert_eq!(roles.len(), 2);
        let channels = [
            Channel::Control,
            Channel::Message,
            Channel::Telemetry,
            Channel::Bulk,
        ];
        assert_eq!(channels.len(), 4);
        assert_ne!(Channel::Control, Channel::Bulk);
    }
}
